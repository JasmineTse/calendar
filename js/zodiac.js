const COLORS = ['月白', '黛蓝', '竹青', '胭脂', '秋香', '藕荷', '朱砂', '石青', '藤黄', '青灰', '缃色', '天水碧'];

function hashStr(s) {
  let h = 2166136261 >>> 0;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619) >>> 0; }
  return h >>> 0;
}

// mulberry32 伪随机数：同一种子得到同一序列，保证运势按日期确定性
function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// 生成某星座某日的运势：综合文案 200–300 字 + 星级 + 幸运信息
export function generateFortune(idx, dateKey) {
  const seed = hashStr(dateKey + '#' + idx);
  const rand = mulberry32(seed);
  const used = new Map();
  const pick = pool => {
    let i;
    do { i = Math.floor(rand() * pool.length); } while (used.has(pool) && used.get(pool).has(i));
    if (!used.has(pool)) used.set(pool, new Set());
    used.get(pool).add(i);
    return pool[i];
  };
  const stars = () => 2 + Math.floor(rand() * 4); // 2–5 星

  const text = [pick(POOLS.overall), pick(POOLS.love), pick(POOLS.career), pick(POOLS.wealth), pick(POOLS.health)].join('');
  // 文案偏短时补一句（最多两句），确保落在 200–300 字区间
  let guard = 0;
  let full = text;
  while (full.length < 225 && guard < 2) { full += pick(POOLS.extra); guard++; }
  full += pick(POOLS.advice);

  const friend = ZODIAC[(idx + 3 + Math.floor(rand() * 10)) % 12].name;
  return {
    text: full,
    ratings: { overall: stars(), love: stars(), career: stars(), wealth: stars(), health: stars() },
    color: COLORS[Math.floor(rand() * COLORS.length)],
    num: 1 + Math.floor(rand() * 99),
    friend
  };
}
