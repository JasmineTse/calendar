// 每日一问：按日期确定性选取（同一天人人相同，每天不同）
export function whyOfTheDay(key) {
  let h = 0;
  const s = 'why:' + key;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  return WHYS[h % WHYS.length];
}

// 随机选一个，避免与当前重复
export function randomWhyIndex(exceptIdx) {
  if (WHYS.length <= 1) return 0;
  let i = Math.floor(Math.random() * WHYS.length);
  while (i === exceptIdx) i = (i + 1) % WHYS.length;
  return i;
}
